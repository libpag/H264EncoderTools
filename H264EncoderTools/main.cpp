/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  H264EncoderTools: Standalone x264 encoding helper for TAVPAGConvertor.
//
//  This tool runs as a SEPARATE PROCESS from PAGConvertor in order to keep the GPL-licensed
//  libx264 isolated from the Apache-2.0-licensed main program. Communication happens through a
//  file-handshake protocol (backward compatible with the original tool).
//
//  Protocol (files exchanged under a working directory, passed as argv[1]):
//    [Host -> Tool]  EncoderParam.txt      {"Width","Height","FrameRate","HasAlpha",
//                                           "MaxKeyFrameInterval","Quality",
//                                           optional "OriginalWidth","OriginalHeight",
//                                           optional "Deterministic"}
//    [Host -> Tool]  YUV-<n>.yuv           raw YUV420p frame (packed, no padding)
//    [Host -> Tool]  InFrameInfo-<n>.txt   {"FrameType","TimeStamp","FrameSize"}
//    [Host -> Tool]  InEnd.txt             {"HasEnd","EarlyExit"}  (flush signal)
//    [Tool -> Host]  Header-0.dat          SPS
//    [Tool -> Host]  Header-1.dat          PPS
//    [Tool -> Host]  H264-<n>.264          encoded H.264 Annex-B stream for frame n
//    [Tool -> Host]  OutFrameInfo-<n>.txt  {"FrameType","TimeStamp","FrameSize"}
//    [Tool -> Host]  OutEnd.txt            {"HasEnd","EarlyExit"}  (+optional "Error","ErrorMessage")
//
//  The encoding parameters (preset, CRF, VBV, keyint, level, refs, VUI) are aligned with the AE
//  export plugin (PAGExporter) at the parameter level; each deviating or plugin-specific choice is
//  commented at the assignment site below. The optional "Deterministic" field is the only runtime
//  switch that departs from that alignment (thread count only), and it defaults to off.
//  NOTE: x264 library version-level identity with the AE plugin has not been independently verified.
//
/////////////////////////////////////////////////////////////////////////////////////////////////

